/**
 * Получить случайную реплику Спарка с подстановкой контекста
 */
export function getRandomReplica(category: string, context?: ReplicaContext): string {
  const list = SPARK_REPLICAS[category] || SPARK_REPLICAS.greeting;
  const raw = list[Math.floor(Math.random() * list.length)];
  let res = raw;
  if (context?.userName) {
    res = res.replace('{userName}', context.userName);
  }
  if (context?.studioName) {
    res = res.replace('{studioName}', context.studioName);
  }
  return res;
}
